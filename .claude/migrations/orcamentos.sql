-- ── RLS: orcamento_modelos ──────────────────────────────────────────────────
alter table public.orcamento_modelos enable row level security;

create policy "orcamento_modelos_select"
  on public.orcamento_modelos for select
  to authenticated
  using (true);

create policy "orcamento_modelos_insert"
  on public.orcamento_modelos for insert
  to authenticated
  with check (auth.uid() = created_by);

create policy "orcamento_modelos_update"
  on public.orcamento_modelos for update
  to authenticated
  using (true);

create policy "orcamento_modelos_delete"
  on public.orcamento_modelos for delete
  to authenticated
  using (true);

-- ── RLS: orcamento_configuracoes ────────────────────────────────────────────
alter table public.orcamento_configuracoes enable row level security;

create policy "orcamento_configuracoes_select"
  on public.orcamento_configuracoes for select
  to authenticated
  using (true);

create policy "orcamento_configuracoes_insert"
  on public.orcamento_configuracoes for insert
  to authenticated
  with check (true);

create policy "orcamento_configuracoes_update"
  on public.orcamento_configuracoes for update
  to authenticated
  using (true);

-- ── RLS: orcamentos ──────────────────────────────────────────────────────────
alter table public.orcamentos enable row level security;

create policy "orcamentos_select"
  on public.orcamentos for select
  to authenticated
  using (true);

create policy "orcamentos_insert"
  on public.orcamentos for insert
  to authenticated
  with check (auth.uid() = created_by);

create policy "orcamentos_update"
  on public.orcamentos for update
  to authenticated
  using (true);

create policy "orcamentos_delete"
  on public.orcamentos for delete
  to authenticated
  using (true);

-- ── GRANTs: sem isso o RLS acima nunca é avaliado, o Postgres barra antes ──
-- (retorna 42501 "permission denied for table X" mesmo com policy "using (true)")
grant select, insert, update, delete on public.orcamento_modelos to authenticated;
grant select, insert, update, delete on public.orcamento_configuracoes to authenticated;
grant select, insert, update, delete on public.orcamentos to authenticated;
